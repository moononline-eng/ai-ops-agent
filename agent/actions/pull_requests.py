"""Validate a proposed patch in a scratch copy, then open a DRAFT pull request.

Steps:
  1. Copy the repo to a temp dir (the real working tree is never modified).
  2. `git apply --check` then `git apply` (refuses paths outside the tree).
  3. Run the test suite against the patched copy with a scrubbed environment
     (no API keys or tokens), a timeout, and no access to the real repo.
  4. Only if tests pass: create branch agent/<fingerprint>, upload the changed
     files through the REST API, open a draft PR that links the issue.

Note on step 3: running tests executes code the model wrote. That's why this
must run in a disposable container or CI runner, never on a production host.
"""

import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from agent.analyzer import Finding
from agent.policy import patch_paths

COPY_IGNORE = shutil.ignore_patterns(".git", ".venv", "logs", "audit", "reports", "__pycache__", ".env*", ".agent_state.json")
TEST_TIMEOUT_S = 300


@dataclass
class PatchResult:
    ok: bool
    log: str
    workdir: Path | None = None


def _run(cmd: list[str], cwd: Path, timeout: int) -> subprocess.CompletedProcess:
    # Minimal environment: nothing secret is inherited by model-written code.
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(cwd), "PYTHONPATH": str(cwd)}
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout, check=False)


def validate_patch(repo_root: Path, patch: str) -> PatchResult:
    workdir = Path(tempfile.mkdtemp(prefix="ops-agent-"))
    shutil.copytree(repo_root, workdir, ignore=COPY_IGNORE, dirs_exist_ok=True)
    patch_file = workdir / ".agent.patch"
    patch_file.write_text(patch if patch.endswith("\n") else patch + "\n")

    for args in (["--check"], []):
        r = _run(["git", "apply", *args, ".agent.patch"], workdir, 60)
        if r.returncode != 0:
            return PatchResult(False, f"git apply {' '.join(args)} failed:\n{r.stderr[-2000:]}", workdir)
    patch_file.unlink()

    try:
        r = _run([sys.executable, "-m", "pytest", "-q", "-x"], workdir, TEST_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return PatchResult(False, f"tests timed out after {TEST_TIMEOUT_S}s", workdir)
    output = (r.stdout + r.stderr)[-3000:]
    return PatchResult(r.returncode == 0, output, workdir)


def open_draft_pr(gh, f: Finding, result: PatchResult, base: str, issue: dict | None) -> dict:
    files = sorted(p for p in patch_paths(f.patch) if (result.workdir / p).is_file())
    title = f"[ops-agent] Fix: {f.title}"
    if not hasattr(gh, "create_branch"):  # dry-run client
        return gh.propose_pr(title, files)

    branch = f"agent/{f.fingerprint}"
    gh.create_branch(branch, gh.branch_sha(base))
    for path in files:
        gh.put_file(
            path,
            (result.workdir / path).read_bytes(),
            branch,
            f"ops-agent: {f.title}",
            gh.file_sha(path, branch),
        )
    issue_ref = f"Refs #{issue['number']}\n\n" if issue else ""
    body = (
        f"{issue_ref}**Root cause:** {f.root_cause}\n\n**Fix:** {f.suggested_fix}\n\n"
        f"Agent confidence: {f.confidence:.0%}. Tests passed in the agent's sandbox:\n"
        f"```\n{result.log[-1500:]}\n```\n\n"
        "> Draft PR generated by ai-ops-agent. A human must review, and CI must pass, before merging."
    )
    return gh.create_draft_pr(title, body, branch, base)
